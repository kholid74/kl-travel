// Downloads the curated Unsplash photos listed in sources.json, resizes them for the web,
// and generates src/data/fixtures/media.generated.ts (dimensions, blur placeholders, credits).
//
//   node scripts/media/fetch-media.mjs
//
// Photos are used under the Unsplash License (https://unsplash.com/license). Unsplash+ photos
// are excluded. Files that already exist are not downloaded again.

import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import sharp from "sharp"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..")
const sources = JSON.parse(fs.readFileSync(path.join(root, "scripts/media/sources.json"), "utf8"))
const MAX_EDGE = 2000

const FOLDERS = {
  lbj: "labuan-bajo",
  np: "nusa-penida",
  bali: "bali",
  lbk: "lombok",
  ra: "raja-ampat",
  brm: "bromo",
  yog: "yogyakarta",
  blt: "belitung",
}

const entries = []
for (const source of sources) {
  const folder = FOLDERS[source.id.split("-")[0]]
  if (!folder) throw new Error(`No folder for ${source.id}`)
  const relative = `images/${folder}/${source.id}.jpg`
  const file = path.join(root, "public", relative)
  fs.mkdirSync(path.dirname(file), { recursive: true })

  if (!fs.existsSync(file)) {
    const url = `https://images.unsplash.com/photo-${source.imgId}?fm=jpg&q=90&w=2400`
    const res = await fetch(url, { headers: { "User-Agent": "Mozilla/5.0 (media script)" } })
    if (!res.ok) throw new Error(`${source.id}: HTTP ${res.status}`)
    const input = Buffer.from(await res.arrayBuffer())
    await sharp(input)
      .rotate()
      .resize({ width: MAX_EDGE, height: MAX_EDGE, fit: "inside", withoutEnlargement: true })
      .jpeg({ quality: 74, mozjpeg: true, progressive: true })
      .toFile(file)
    console.log("downloaded", relative)
  }

  const meta = await sharp(file).metadata()
  const blur = await sharp(file).resize(16, 16, { fit: "inside" }).jpeg({ quality: 50 }).toBuffer()
  entries.push({
    id: `img-${source.id}`,
    src: `/${relative}`,
    width: meta.width,
    height: meta.height,
    alt: source.alt,
    blurDataURL: `data:image/jpeg;base64,${blur.toString("base64")}`,
    credit: { photographer: source.photographer, sourceUrl: `https://unsplash.com/photos/${source.photoId}` },
    tags: source.tags,
  })
}

const out = `// Generated by scripts/media/fetch-media.mjs — do not edit by hand.
import type { MediaAsset } from "@/domain/entities"

export const MEDIA_ASSETS: MediaAsset[] = ${JSON.stringify(entries, null, 2)}
`
fs.writeFileSync(path.join(root, "src/data/fixtures/media.generated.ts"), out)
const bytes = entries.reduce((sum, e) => sum + fs.statSync(path.join(root, "public", e.src)).size, 0)
console.log(`${entries.length} assets, ${(bytes / 1024 / 1024).toFixed(1)} MB`)
